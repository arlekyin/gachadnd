const plainText = html => String(html ?? '').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ');

/**
 * Термины, встречающиеся в тексте, и пояснения тегов синергий.
 * @param {string} html            Описание навыка.
 * @param {string[]} tags          Теги навыка.
 * @param {Record<string, number>} tagCounts  Число экипированных навыков с каждым тегом.
 * @returns {{ title: string, text: string, accent?: boolean }[]}
 */
export function collectGlossary(html, tags = [], tagCounts = {}) {
    const text = plainText(html);
    const entries = [];

    const dictionary = getSynergyDictionary('');
    for (const tag of tags) {
        const config = dictionary[tag];
        if (!config) continue;
        const count = tagCounts[tag] ?? 0;
        const steps = config.thresholds
            .map(t => `${count >= t.count ? '◆' : '◇'} ${t.count}: ${t.name.split(': ')[1] ?? t.name}`)
            .join('<br>');
        entries.push({
            title: t('Тег «{tag}» · экипировано {count}', { tag, count }),
            text: steps,
            accent: true
        });
    }

    // «ПЗ» отдельной карточкой — только если они встречаются не в составе «временных ПЗ»
    const withoutTempHp = text.replace(/временн\S* ПЗ/gi, '');
    for (const term of TERMS) {
        const source = term.title === 'ПЗ' ? withoutTempHp : text;  // i18n: данные
        if (term.match.test(source)) entries.push({ title: term.title, text: term.text });
    }
    return entries;
}
